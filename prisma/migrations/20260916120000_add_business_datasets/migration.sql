CREATE TABLE `business_datasets` (
    `id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
    `imported_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    `source` VARCHAR(255) NOT NULL,
    `dataset` VARCHAR(255) NOT NULL,
    `area` VARCHAR(255) NOT NULL,
    `primary_source` VARCHAR(255) NOT NULL,
    `enrichment_source` VARCHAR(255) NOT NULL,
    `rules` JSON NOT NULL,
    `counts` JSON NOT NULL,
    `active` BOOLEAN NOT NULL DEFAULT true,
    PRIMARY KEY (`id`),
    INDEX `business_datasets_active_imported_at_idx`(`active`, `imported_at`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `businesses` (
    `id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
    `dataset_id` INTEGER UNSIGNED NOT NULL,
    `key` VARCHAR(255) NOT NULL,
    `name` VARCHAR(255) NOT NULL,
    `category` VARCHAR(255) NULL,
    `secondary_category` VARCHAR(255) NULL,
    `address` VARCHAR(1024) NULL,
    `locality` VARCHAR(255) NULL,
    `postal_code` VARCHAR(32) NULL,
    `phone` VARCHAR(128) NULL,
    `website` VARCHAR(2048) NULL,
    `rating` DOUBLE NULL,
    `review_count` INTEGER NULL,
    `hours_summary` TEXT NULL,
    `plus_code` VARCHAR(128) NULL,
    `latitude` DOUBLE NULL,
    `longitude` DOUBLE NULL,
    `notes` JSON NOT NULL,
    `google_maps_url` VARCHAR(2048) NULL,
    `queries_discovered_via` JSON NOT NULL,
    `collected_at` VARCHAR(64) NULL,
    `location_match` VARCHAR(64) NULL,
    `location_reason` TEXT NULL,
    `smb_likelihood` VARCHAR(64) NULL,
    `smb_confidence` VARCHAR(64) NULL,
    `smb_reason` TEXT NULL,
    `sources` JSON NOT NULL,
    PRIMARY KEY (`id`),
    UNIQUE INDEX `businesses_dataset_id_key_key`(`dataset_id`, `key`),
    INDEX `businesses_dataset_id_idx`(`dataset_id`),
    CONSTRAINT `businesses_dataset_id_fkey` FOREIGN KEY (`dataset_id`) REFERENCES `business_datasets`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `openstreetmap_records` (
    `id` INTEGER UNSIGNED NOT NULL AUTO_INCREMENT,
    `business_id` INTEGER UNSIGNED NOT NULL,
    `osm_type` VARCHAR(32) NOT NULL,
    `osm_id` BIGINT UNSIGNED NOT NULL,
    `name` VARCHAR(255) NULL,
    `category` VARCHAR(255) NULL,
    `address` VARCHAR(1024) NULL,
    `phone` VARCHAR(128) NULL,
    `website` VARCHAR(2048) NULL,
    `opening_hours` TEXT NULL,
    `latitude` DOUBLE NULL,
    `longitude` DOUBLE NULL,
    `osm_tags` JSON NULL,
    `match_name_similarity` DOUBLE NULL,
    `match_distance_m` DOUBLE NULL,
    PRIMARY KEY (`id`),
    INDEX `openstreetmap_records_business_id_idx`(`business_id`),
    INDEX `openstreetmap_records_osm_type_osm_id_idx`(`osm_type`, `osm_id`),
    CONSTRAINT `openstreetmap_records_business_id_fkey` FOREIGN KEY (`business_id`) REFERENCES `businesses`(`id`) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
